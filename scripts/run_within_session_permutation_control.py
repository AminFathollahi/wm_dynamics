def _pre_cue_session_trial_arrays(session: dict, behaviour, seed_prefix: str) -> dict | None:
    """Recomputes exactly the sequence run_pre_cue_state_and_reported_item_identity.py's own
    analyse_session runs to reach its block_a primary statistic -- every one of _object_geometry,
    _landed_and_target_index, _landed_identity_check, _behaviour_observables, _leave_one_out_unit_
    directions, _watters_reachability, usable_label and _ridge_decode is imported unchanged and called
    in the identical order with the identical arguments -- but additionally returns the trial-level
    decoded_theta_test, reported_theta and other_theta arrays that function computes internally and
    never returns, because those raw arrays (not exposed by the delivered script) are exactly what a
    within-session permutation of this cell needs. Returns None for any session that does not reach
    'computed' status under the identical gates the delivered script applies; the caller cross-checks
    this function's own primary_fraction against the delivered per-session value before trusting it
    (see the reproduction check in _cell_pre_cue_reported_item)."""
    counts = session["counts"]
    activity = counts.sum(axis=2)
    observables, _excluded, usable = _behaviour_observables(counts, session)
    if int(usable.sum()) < MIN_TRIALS_FOR_BEHAVIOURAL_CORRELATION:
        return None

    geometry = _object_geometry(behaviour, session)
    landed_info = _landed_and_target_index(behaviour, session)
    identity = _landed_identity_check(behaviour, session, geometry, landed_info)
    if not identity["swap_primary_matches_object_geometry"]:
        return None

    item_count = np.asarray(session["num_objects"], dtype=float)
    swap_primary = geometry["swap_primary"]
    train_mask = usable & (item_count >= 2) & (~swap_primary)
    test_mask = usable & (item_count == 3) & swap_primary
    analysis_mask = train_mask | test_mask

    cued_theta = np.asarray(session["cued_theta"], dtype=float)
    theta_mod = np.mod(cued_theta, 2.0 * np.pi)
    discretized_label = (np.floor(theta_mod / (2.0 * np.pi / WATTERS_RECOVERABILITY_K_CLASSES)).astype(int)
                          % WATTERS_RECOVERABILITY_K_CLASSES)

    idx_analysis = np.flatnonzero(analysis_mask)
    if idx_analysis.size < MIN_TRIALS_FOR_BEHAVIOURAL_CORRELATION:
        return None
    label_ok, _reason, label_submask = usable_label(
        discretized_label[idx_analysis], min_classes=MIN_CLASSES, min_per_class=MIN_TRIALS_PER_CLASS)
    if not label_ok:
        return None
    final_idx = idx_analysis[label_submask]

    tag = f"{seed_prefix}|{session['session']}"
    gate = _watters_reachability(counts[final_idx], discretized_label[final_idx],
                                  stable_seed(f"{tag}|reachability"))
    if gate.get("status") != "tested" or not gate.get("cleared", False):
        return None

    train_sub = train_mask[final_idx]
    test_sub = test_mask[final_idx]
    if int(train_sub.sum()) < MIN_TRAIN_TRIALS_PER_SESSION or int(test_sub.sum()) < MIN_TEST_TRIALS_PER_SESSION:
        return None

    unit_vectors_all = _leave_one_out_unit_directions(activity)["unit_vectors"]
    u = unit_vectors_all[final_idx]
    target_2d = np.stack([np.cos(cued_theta[final_idx]), np.sin(cued_theta[final_idx])], axis=1)
    object_theta = landed_info["object_theta"][final_idx]
    landed = landed_info["landed"][final_idx]
    target = landed_info["target"][final_idx]
    other_idx = 3 - target - landed

    fold_seed = stable_seed(f"{tag}|ridge_folds")
    decode_full = _ridge_decode(u[train_sub], target_2d[train_sub], u[test_sub], fold_seed)
    if decode_full.get("status") != "computed":
        return None

    n = np.arange(int(test_sub.sum()))
    reported_theta = object_theta[test_sub][n, landed[test_sub]]
    other_theta = object_theta[test_sub][n, other_idx[test_sub]]
    primary = _report_following_fraction(decode_full["decoded_theta_test"], reported_theta, other_theta)

    return {
        "decoded_theta_test": decode_full["decoded_theta_test"], "reported_theta": reported_theta,
        "other_theta": other_theta, "n_test_trials": primary["n_trials"], "primary_fraction": primary["fraction"],
    }


def _pre_cue_shuffle_block(rng: np.random.Generator, block: dict) -> dict:
    """The identical within-session substitution run_pre_cue_state_and_reported_item_identity.py's own
    _shuffled_report_null uses: independently, per trial, flip a coin on whether 'reported' and 'other'
    are swapped, leaving the decoded position (this session's real, trial-varying decode) untouched."""
    flip = rng.random(block["n"]) < 0.5
    reported = np.where(flip, block["other"], block["reported"])
    other = np.where(flip, block["reported"], block["other"])
    return {**block, "reported": reported, "other": other}


def _pre_cue_stat_of_session(blocks: list[dict]) -> float | None:
    block = blocks[0]
    if block["n"] == 0:
        return None
    d_rep = circular_abs_diff(block["decoded"], block["reported"])
    d_oth = circular_abs_diff(block["decoded"], block["other"])
    return float(np.mean(d_rep < d_oth)) - 0.5  # departure from 0.5, matching the delivered mean_diff_from_half scale


def _cell_pre_cue_reported_item() -> dict:
    delivered = json.loads((ROOT / "results" / "pre_cue_state_and_reported_item_identity.json").read_text())
    delivered_per_session = {r["session"]: r["observed_fraction"]
                              for r in delivered["block_a"]["per_session_shuffled_report_null"]}
    delivered_pooled_a = delivered["block_a"]["pooled_a_primary"]
    delivered_pooled_c = delivered["block_a"]["pooled_c_bias_only_control"]

    root = data_root()
    behaviour = watters_behaviour(root)
    session_blocks, mismatches = [], []
    n_seen, n_with_arrays = 0, 0
    for session in iter_watters(root, bin_ms=100.0):
        n_seen += 1
        if session["status"] != "loaded":
            continue
        key = session["session"]
        if key not in delivered_per_session:
            continue  # not one of the 22 sessions the delivered artifact itself analysed to 'computed'
        # seed_prefix must match the delivered script's own literal string exactly: every stable_seed
        # tag derived from it (the reachability gate's own randomness, the ridge decoder's KFold shuffle
        # seed) depends on this string, and a different one silently reproduces a DIFFERENT session
        # population and different fold splits rather than the delivered analysis.
        result = _pre_cue_session_trial_arrays(session, behaviour, "pre_cue_state_and_reported_item_identity")
        if result is None:
            mismatches.append({"session": key, "reason": "recomputation_did_not_reach_computed_status"})
            continue
        n_with_arrays += 1
        if abs(result["primary_fraction"] - delivered_per_session[key]) >= REPRODUCTION_TOLERANCE:
            mismatches.append({"session": key, "recomputed": result["primary_fraction"],
                                "delivered": delivered_per_session[key]})
        session_blocks.append([{
            "n": result["n_test_trials"], "decoded": result["decoded_theta_test"],
            "reported": result["reported_theta"], "other": result["other_theta"],
        }])

    gate_ok = bool(n_with_arrays == len(delivered_per_session) and not mismatches)
    per_session_departure = [_pre_cue_stat_of_session(blocks) for blocks in session_blocks]
    per_session_departure = [v for v in per_session_departure if v is not None]
    real_recomputed_mean = float(np.mean(per_session_departure)) if per_session_departure else None
    reproduction_checks = {
        "n_sessions_matches": bool(n_with_arrays == len(delivered_per_session)),
        "n_sessions_with_exact_fraction_match": len(delivered_per_session) - len(mismatches),
        "recomputed_departure_matches_delivered": bool(
            real_recomputed_mean is not None
            and abs(real_recomputed_mean - delivered_pooled_a["mean_diff_from_half"]) < 1e-6),
    }

    permutation = {"primary": within_session_permutation_test(
        session_blocks, "within_session_permutation_control|pre_cue_reported_item",
        stat_of_session=_pre_cue_stat_of_session, shuffle_block=_pre_cue_shuffle_block)}

    real_reported = {
        "status": "tested", "mean_value": delivered_pooled_a["mean_diff_from_half"],
        "p_value": delivered_pooled_a["p_value"], "significant": delivered_pooled_a["significant"],
        "ci_lower": delivered_pooled_a["ci_lower"] - 0.5, "ci_upper": delivered_pooled_a["ci_upper"] - 0.5,
        "minimum_detectable_paired_difference_at_80pct_power":
            delivered_pooled_a["minimum_detectable_departure_from_half_at_80pct_power"],
    }
    return _assemble_cell(
        cell_name="pre_cue_state_leans_away_from_reported_item",
        corpus="multi_object_macaque_watters", n_sessions=len(session_blocks),
        delivered_artifact="results/pre_cue_state_and_reported_item_identity.json",
        reproduction_checks=reproduction_checks, gate_ok=gate_ok,
        real_by_stat={"primary": real_reported},
        between_session_control_by_stat={"primary": {
            "mean_value": delivered_pooled_c["mean_diff_from_half"], "p_value": delivered_pooled_c["p_value"],
            "significant": delivered_pooled_c["significant"]}},
        permutation_by_stat=permutation,
        why_at_risk="the pre-cue population state's below-half lean toward the object that will be "
                    "reported (not the cued object) -- the delivered decision list has no bias-only "
                    "voiding clause for a below-half departure (a declared gap in the rule), and the "
                    "between-session control fires in the same direction at larger magnitude; the "
                    "delivered artifact itself states this departure 'must never be read as a per-trial "
                    "neural result' on that basis. No spike-count/trial-index nuisance partial exists for "
                    "this fraction-based estimator (it is not a correlation), so only the primary "
                    "statistic is reported, not a raw/joint-partial pair.",
        mismatches=mismatches,
    )


