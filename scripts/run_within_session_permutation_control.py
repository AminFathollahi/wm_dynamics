# ============================================================================
# Generic within-session permutation engine
# ============================================================================

def _cheap_partial_r(outcome: np.ndarray, covariate: np.ndarray, controls: list[np.ndarray]) -> float | None:
    """Point-estimate-only partial Pearson correlation by the residual method (OLS on
    [intercept, *controls], then Pearson on the two residual series) -- the identical formula
    statistics.partial_correlation_permutation_test uses for its own observed statistic, without that
    function's inner permutation loop, because this helper is called once per session on every one of
    N_PERM_WITHIN_SESSION outer draws, where re-running a full permutation test that many times nested
    inside another permutation test is not tractable."""
    outcome = np.asarray(outcome, dtype=float)
    covariate = np.asarray(covariate, dtype=float)
    if controls:
        design = np.column_stack([np.ones(len(outcome)), *[np.asarray(c, dtype=float) for c in controls]])
        y_resid = outcome - design @ np.linalg.lstsq(design, outcome, rcond=None)[0]
        x_resid = covariate - design @ np.linalg.lstsq(design, covariate, rcond=None)[0]
    else:
        y_resid, x_resid = outcome - outcome.mean(), covariate - covariate.mean()
    if np.std(y_resid) == 0.0 or np.std(x_resid) == 0.0:
        return None
    return float(np.corrcoef(y_resid, x_resid)[0, 1])


def _default_shuffle_block(rng: np.random.Generator, block: dict) -> dict:
    perm = rng.permutation(block["n"])
    return {**block, "outcome": block["outcome"][perm]}


def _circular_outcome_shift(rng: np.random.Generator, block: dict) -> dict:
    shift = int(rng.integers(1, block["n"]))
    return {**block, "outcome": np.roll(block["outcome"], shift)}


def _circular_residual_shift(rng: np.random.Generator, block: dict) -> dict:
    if not block["controls"]:
        return _circular_outcome_shift(rng, block)
    design = np.column_stack([np.ones(block["n"]), *block["controls"]])
    fitted = design @ np.linalg.lstsq(design, block["outcome"], rcond=None)[0]
    residual = block["outcome"] - fitted
    shift = int(rng.integers(1, block["n"]))
    return {**block, "outcome": fitted + np.roll(residual, shift)}


def _default_stat_of_session(blocks: list[dict]) -> float | None:
    """Trial-count-weighted average of each block's own partial correlation -- the identical
    combination rule run_component_and_item_binding.py's _outcome_arm uses to pool a session's own
    per-item-count-level correlations into one within_item_count_level_trial_count_weighted number."""
    weighted, total_n = [], 0
    for block in blocks:
        r = _cheap_partial_r(block["outcome"], block["predictor"], block["controls"])
        if r is None:
            continue
        weighted.append(block["n"] * r)
        total_n += block["n"]
    if total_n == 0:
        return None
    return float(sum(weighted) / total_n)


def within_session_permutation_test(session_blocks: list[list[dict]], seed_tag: str,
                                     n_perm: int = N_PERM_WITHIN_SESSION,
                                     stat_of_session=_default_stat_of_session,
                                     shuffle_block=_default_shuffle_block) -> dict:
    """session_blocks: one entry per session; each entry is a list of blocks (one block per item-count
    level a session's own real statistic pools across; a session with no level structure has exactly
    one block). stat_of_session(blocks) -> the session's own composite statistic (or None). On every
    permutation draw, shuffle_block is applied INDEPENDENTLY to every block of every session (default:
    permutes which trial gets which outcome, inside that block only), session identity, session sizes
    and every between-session and between-block structure held fixed; the pooled statistic (unweighted
    mean of the per-session composites -- the identical pooling statistic
    state_persistence.slope_across_sessions_test's own sign-flip test uses, paired_sign_flip_test's
    mean_diff) is recomputed on every draw to build the null. Two-sided permutation p-value, +1/+1
    corrected (statistics.permutation_pvalue)."""
    rng = np.random.default_rng(stable_seed(seed_tag))
    observed_per_session = [stat_of_session(blocks) for blocks in session_blocks]
    observed_per_session = [v for v in observed_per_session if v is not None]
    if len(observed_per_session) < 2:
        return {"status": "not_computable", "n_sessions_contributing": len(observed_per_session),
                "reason": "fewer than 2 sessions contribute a computable composite value"}
    observed_pooled = float(np.mean(observed_per_session))

    null = np.full(n_perm, np.nan)
    for draw in range(n_perm):
        draw_values = []
        for blocks in session_blocks:
            shuffled = [shuffle_block(rng, block) for block in blocks]
            v = stat_of_session(shuffled)
            if v is not None:
                draw_values.append(v)
        if draw_values:
            null[draw] = float(np.mean(draw_values))
    valid = np.isfinite(null)
    p_value = permutation_pvalue(np.abs(null[valid]) >= abs(observed_pooled))
    return {
        "status": "computed", "n_sessions_contributing": len(observed_per_session),
        "observed_pooled_statistic": observed_pooled,
        "direction": "positive" if observed_pooled > 0 else "negative" if observed_pooled < 0 else "zero",
        "n_permutations_requested": n_perm, "n_permutations_valid": int(valid.sum()),
        "min_attainable_p_value": 1.0 / (n_perm + 1), "p_value": p_value,
        "significant": bool(p_value < ALPHA),
    }


