"""run_within_session_permutation_control.py -- for every cell this project's
between-session bias-only control voided or left the whole claim untested,
apply a control that CAN confound a within-session estimator: a within-
session permutation of the trial-to-outcome assignment.

WHY. results/bias_only_control_validity_simulation.json demonstrates, by
simulation with known ground truth, that the between-session bias-only
control used throughout this project's behavioural analyses (results/
component_binding_bias_only_control.json, results/swap_versus_imprecision_
by_item_count.json, results/pre_cue_state_and_reported_item_identity.json,
results/behaviour_association_bias_only_sweep.json) cannot distinguish a
real within-session effect from a session-level offset when both are
present at once: the between-session statistic it checks is computed
entirely from cluster (session) means, the within-session statistic is
computed entirely from within-cluster deviations, and the two components of
total covariance are free to vary independently. A voiding built on that
control alone is therefore not evidence against the within-session claim --
it rests on an estimator that cannot confound it.

THE VALID CONTROL. Within each session, shuffle the trial-to-outcome
assignment -- session identity, session means, session sizes and every
between-session structure are left EXACTLY as observed; only which trial
gets which outcome, inside that session (inside each item-count level
separately, where the real statistic pools trial-count-weighted across
levels), is randomised. The full pooled statistic (the same estimator, same
pooling rule, as the real claim) is recomputed on every permutation to build
a null distribution entirely generated by within-session shuffling. If the
real effect's magnitude sits outside that null, session identity cannot
explain it, because session identity was held fixed by construction on
every single draw.

CELLS COVERED (located by searching results/*.json for the delivered
voiding branch names and for keys containing "bias"; enumerated in
full in the output's cells_enumerated block):
  A. component_and_item_binding / component_binding_bias_only_control --
     the pooled, within-item-count-level (levels 2 and 3, trial-count
     weighted) swap association: multi-object macaque corpus, 41 sessions.
     VOIDED by the between-session control (raw statistic).
  B. swap_versus_imprecision_by_item_count -- the identical association at
     the single item-count level 2 grain. VOIDED by the between-session
     control.
  C. pre_cue_state_and_reported_item_identity -- the pre-cue state's
     below-half lean toward the item that will be reported (block_a,
     primary statistic). The delivered decision list has no bias-only
     clause on this branch (a declared gap, not an omission), and the
     bias-only control fires in the same direction at larger magnitude --
     the artifact's own text states the departure "must never be read as a
     per-trial neural result" on that basis.
  D. rate_free_state_geometry_behavior_link (surviving half of this
     project's headline dissociation, cited inside results/behaviour_
     association_bias_only_sweep.json) -- NOT voided (the between-session
     control did not reach significance), but the sweep's own cluster
     bootstrap shows that control was itself underpowered (MDD 0.82 r
     units against a 0.14 reference, while observing r=-0.44 in the
     confounding direction): the sweep's own verdict is that this claim is
     UNTESTED against session identity, not confirmed clean of it.

FRAMING, held throughout this module and its output. A cell whose voiding
rests on the between-session control alone is reported as UNRESOLVED --
neither established nor validly withdrawn -- never as "restored" or
"confirmed". A cell becomes positive again only if it independently
survives the within-session permutation control at its own pre-declared
threshold below, and even then it is reported with its effect size and its
detection floor, never as a return to the pre-voiding status quo.

DECISION RULE, declared before any cell is fitted (BRANCH_DECISION_RULE_
DECLARED_BEFORE_FITTING below): a per-cell branch in terms of the
within-session permutation control, including an explicit inconclusive
outcome, applied identically to every cell.

No corpus loader, per-session correlation estimator, ridge decoder or
reachability gate is forked: every one of iter_watters, watters_behaviour,
_session_arrays, _ridge_decode, _report_following_fraction,
_landed_and_target_index, _landed_identity_check, _object_geometry,
_leave_one_out_unit_directions, _watters_reachability, usable_label,
_behaviour_observables, rate_free_session_arrays, _reachable_sessions
(the Panichello loader) and slope_across_sessions_test is imported
unchanged from the delivered script that already uses it. The only new
code here is the within-session permutation engine itself and the
per-cell wiring that hands it each cell's own trial-level arrays.
"""

