def _assemble_cell(cell_name, corpus, n_sessions, delivered_artifact, reproduction_checks, gate_ok,
                    real_by_stat, between_session_control_by_stat, permutation_by_stat, why_at_risk,
                    zero_drop_note=None, mismatches=None) -> dict:
    cell = {
        "cell_name": cell_name, "corpus": corpus, "n_sessions": n_sessions,
        "delivered_artifact": delivered_artifact, "why_at_risk": why_at_risk,
        "reproduction_gate": {"status": "reproduced" if gate_ok else "not_reproduced",
                               "tolerance": REPRODUCTION_TOLERANCE, "checks": reproduction_checks},
    }
    if zero_drop_note:
        cell["zero_drop_note"] = zero_drop_note
    if mismatches is not None:
        cell["reproduction_mismatches"] = mismatches
    if not gate_ok:
        cell["branch"] = BRANCH_GATE_FAILED
        return cell

    stats = list(real_by_stat.keys())
    real_significant = {s: bool(real_by_stat[s].get("significant")) for s in stats}
    real_direction = {s: ("positive" if (real_by_stat[s].get("mean_value") or 0) > 0 else "negative")
                       for s in stats}
    all_real_significant = all(real_significant.values())

    cell["real"] = real_by_stat
    cell["between_session_control_invalid"] = {
        **between_session_control_by_stat,
        "validity_note": "this control cannot confound a within-session estimator (see results/"
                          "bias_only_control_validity_simulation.json); reported here for completeness "
                          "only, never as evidence for or against this cell.",
    }
    cell["within_session_permutation_control_valid"] = permutation_by_stat

    if not all_real_significant:
        cell["branch"] = BRANCH_REAL_NOT_SIGNIFICANT
        cell["branch_significance_by_stat"] = real_significant
        return cell

    survives = all(
        permutation_by_stat[s].get("status") == "computed" and permutation_by_stat[s]["significant"]
        and permutation_by_stat[s]["direction"] == real_direction[s]
        for s in stats
    )
    if survives:
        cell["branch"] = BRANCH_SURVIVES
        return cell

    mdds = [real_by_stat[s].get("minimum_detectable_paired_difference_at_80pct_power", {}).get("mdd")
            for s in stats]
    mdds = [m for m in mdds if isinstance(m, (int, float))]
    if mdds and max(mdds) < MEANINGFUL_EFFECT_THRESHOLD_R_UNITS:
        cell["branch"] = BRANCH_POWERED_NULL
        cell["max_minimum_detectable_difference_across_load_bearing_stats"] = max(mdds)
    else:
        cell["branch"] = BRANCH_INCONCLUSIVE_UNDERPOWERED
    return cell


